"""ULID generation (sortable, unique ids for projects and runs). No dependency needed."""

from __future__ import annotations

import os
import time

_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"  # Crockford base32


def ulid(timestamp_ms: int | None = None) -> str:
    """Return a 26-char ULID: 48-bit ms timestamp + 80 bits of randomness."""
    ts = int(time.time() * 1000) if timestamp_ms is None else timestamp_ms
    value = (ts << 80) | int.from_bytes(os.urandom(10), "big")
    chars = []
    for _ in range(26):
        chars.append(_ALPHABET[value & 31])
        value >>= 5
    return "".join(reversed(chars))
